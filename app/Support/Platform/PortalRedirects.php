<?php

declare(strict_types=1);

namespace App\Support\Platform;

use Illuminate\Routing\Route;
use Illuminate\Routing\Router;

/**
 * The portal host's redirects for links from before the switch — M253 (`R-43038865`, `D236`, runbook §8.3).
 *
 * Until the switch, `iconnect.com.de` WAS iConnect Collection (every path but `/bhw-connect`), with BHW Connect under
 * `/bhw-connect`. After it, `iconnect.com.de` is the portal, Collection is `collection.iconnect.com.de` and Analytics is
 * `analytics.iconnect.com.de`. So the links people already hold — a shared form link, a printed QR code, a bookmark —
 * must reach their new host. Collection's half is every first path segment its route table serves on a workspace host
 * (read here, so a route added before the switch is never missed) plus the static folders its pages load from; BHW's
 * half is `/bhw-connect` and everything under it.
 *
 * What stays on the portal host, and so is never in the list:
 *  - the central routes this app serves there (`admin` — the console, loopback only — `oauth` and Google's `auth`);
 *  - the portal's own root, and its `favicon.ico` and `robots.txt`;
 *  - `sw.js`, which the portal answers with the retiring worker instead (`public/sw-retire.js`);
 *  - the BARE `/explore` and `/feedback`, which are the portal's (Analytics') own pages there. Collection's pages of
 *    those names had sub-paths too, and those still redirect.
 */
final class PortalRedirects
{
    /** First segments that are this app's central routes on the portal host, or the portal's own. */
    public const STAYS = ['', 'admin', 'oauth', 'auth', 'sw.js', 'favicon.ico', 'robots.txt'];

    /** Collection paths whose BARE form is a page of the portal's own on that host (BHW Connect's). */
    public const BARE_IS_THE_PORTALS = ['explore', 'feedback'];

    /** The folders under `public/` that this app's pages load from. */
    public const STATIC_FOLDERS = ['build', 'fonts', 'icons', 'images'];

    public function __construct(private readonly Router $router) {}

    /**
     * Every first path segment (or `api/<group>`) this app answers on a workspace host, sorted.
     *
     * @return list<string>
     */
    public function collectionPrefixes(): array
    {
        $prefixes = self::STATIC_FOLDERS;

        foreach ($this->router->getRoutes()->getRoutes() as $route) {
            $prefix = $this->prefixOf($route);

            if ($prefix !== null) {
                $prefixes[] = $prefix;
            }
        }

        $prefixes = array_values(array_unique($prefixes));
        sort($prefixes);

        return $prefixes;
    }

    /**
     * The routing lines for the PUBLIC portal vhost (`*:443`, `iconnect.com.de`), which serves no page of this app.
     *
     * The console and this app's other central routes are served on that name by a separate LOOPBACK-ONLY vhost
     * (`127.0.0.1:443`), which the box's hosts file reaches and the outside world cannot (runbook §8.5). So nothing
     * here needs to carve this app's paths out of the proxy: from outside, every one of them redirects.
     */
    public function apacheBlock(string $collectionHost, string $analyticsHost): string
    {
        $whole = [];
        $subOnly = [];

        foreach ($this->collectionPrefixes() as $prefix) {
            if (in_array($prefix, self::BARE_IS_THE_PORTALS, true)) {
                $subOnly[] = preg_quote($prefix, '#');
            } else {
                $whole[] = preg_quote($prefix, '#');
            }
        }

        $lines = [
            '# Generated by `php artisan portal:redirects` from iConnect Collection\'s route table (M253, D236).',
            '# The routing of the PUBLIC portal vhost (*:443, iconnect.com.de); regenerate it rather than edit it.',
            '# mod_rewrite runs before ProxyPass, so every redirect below is decided before the proxy is.',
            'RewriteEngine On',
            '# Old form pages kept a service worker at /sw.js: answer it with the one that removes itself.',
            'RewriteRule "^/sw\.js$" "/sw-retire.js" [L]',
            '# The old address of BHW Connect: its home is the portal now, every other page is on Analytics.',
            'RewriteRule "^/bhw-connect/?$" "/" [R=301,L]',
            "RewriteRule \"^/bhw-connect/(.*)$\" \"https://{$analyticsHost}/\$1\" [R=301,L,NE]",
            '# The old address of iConnect Collection: every path it served, to the same path and query there.',
            "RewriteRule \"^/(api/v1|api/platform)(/.*)?$\" \"https://{$collectionHost}%{REQUEST_URI}\" [R=308,L,NE]",
            'RewriteRule "^/('.implode('|', array_diff($whole, ['api/v1', 'api/platform'])).")(/.*)?$\" \"https://{$collectionHost}%{REQUEST_URI}\" [R=301,L,NE]",
        ];

        if ($subOnly !== []) {
            $lines[] = '# Pages whose bare path is the portal\'s own here: only what was under them moves.';
            $lines[] = 'RewriteRule "^/('.implode('|', $subOnly).")/.+$\" \"https://{$collectionHost}%{REQUEST_URI}\" [R=301,L,NE]";
        }

        array_push(
            $lines,
            '# Everything else is the portal: BHW Connect\'s app, at the root, with no base path.',
            '# The retiring worker is a file in this vhost\'s DocumentRoot (iConnect Collection\'s public folder).',
            'ProxyPreserveHost On',
            'ProxyPass /sw-retire.js !',
            'ProxyPass / http://127.0.0.1:3100/ retry=0 timeout=120',
            'ProxyPassReverse / http://127.0.0.1:3100/',
            'RequestHeader set X-Forwarded-Proto "https"',
        );

        return implode("\n", $lines)."\n";
    }

    private function prefixOf(Route $route): ?string
    {
        // A route bound to a domain is a central route (the console, the connectors' callbacks): it stays.
        if ($route->getDomain() !== null) {
            return null;
        }

        $segments = explode('/', trim($route->uri(), '/'));
        $first = $segments[0];

        if (in_array($first, self::STAYS, true) || str_starts_with($first, '{')) {
            return null;
        }

        if ($first === 'api') {
            return isset($segments[1]) && ! str_starts_with($segments[1], '{') ? 'api/'.$segments[1] : null;
        }

        return $first;
    }
}
