-- 1. The two dataset records get the names users see everywhere else. Slugs stay
--    (bhw-stepzero-2026, bhw-2025): they are identifiers, and shared links and cache keys carry them.
update dim_dataset
set
  name = 'BHW Headcount 2025',
  source_name = 'Department of Health (DOH) BHW Connect — BHW Headcount 2025, the LGU-reported count of all BHWs collected before the 2025 individual profiling began (same initiative as BHW Profiles 2025)'
where slug = 'bhw-stepzero-2026';

update dim_dataset
set name = 'BHW Profiles 2025'
where slug = 'bhw-2025';

-- 2. The assistant's dataset dictionary. Phrase by phrase, most specific first, then a fallback for
--    the bare word. replace() is case-sensitive, so lowercase identifiers quoted in the same prose
--    (agg_bhw_stepzero_counts, bhw-stepzero-2026, ingest_stepzero.py) are never touched — the test
--    lib/db/bhw-display-names-migration.test.ts holds that, and that no old name survives.
--    A replace on text that holds no match is a no-op, so this is safe to run on whatever the live
--    rows say, including any admin edit.
do $$
declare
  pairs text[][] := array[
    ['StepZero quick-count by geography', 'BHW Headcount 2025 by geography'],
    ['The DOH StepZero barangay headcount baseline', 'BHW Headcount 2025, the LGU-reported barangay headcount baseline'],
    ['the DOH StepZero universe', 'the BHW Headcount 2025 universe'],
    ['the StepZero BHW headcount', 'the BHW Headcount 2025 count'],
    ['the StepZero headcount rather than the per-person census', 'BHW Headcount 2025 rather than the per-person BHW Profiles 2025'],
    ['the StepZero headcount', 'BHW Headcount 2025'],
    ['THE PROFILED CENSUS', 'BHW PROFILES 2025'],
    ['the profiled census', 'BHW Profiles 2025'],
    ['per-person census', 'per-person BHW Profiles 2025'],
    ['the quick count', 'the headcount'],
    ['quick-count', 'headcount'],
    ['quick count', 'headcount'],
    ['BHW census', 'BHW Profiles 2025'],
    ['BHW Census', 'BHW Profiles 2025'],
    ['LGU-declared', 'LGU-reported'],
    ['StepZero', 'BHW Headcount 2025']
  ];
  i int;
begin
  for i in 1 .. array_length(pairs, 1) loop
    update dataset_registry set title = replace(title, pairs[i][1], pairs[i][2])
      where strpos(title, pairs[i][1]) > 0;
    update dataset_registry set summary = replace(summary, pairs[i][1], pairs[i][2])
      where strpos(summary, pairs[i][1]) > 0;
    update dataset_registry set notes_md = replace(notes_md, pairs[i][1], pairs[i][2])
      where strpos(notes_md, pairs[i][1]) > 0;
    update dataset_column set meaning = replace(meaning, pairs[i][1], pairs[i][2])
      where strpos(meaning, pairs[i][1]) > 0;
  end loop;
end
$$;

-- 3. Expire the AI's cached answers and place summaries written under the old wording, by the app's
--    own mechanism (lib/db/dataset-version.ts): the cache key carries the dataset's last_updated_at,
--    so a new stamp makes every old entry miss. Admin-approved answers are regenerated by the nightly
--    refresh (lib/ai/ask-refresh.ts); the rest regenerate on the next ask. Nothing is deleted here.
--    bhw-2025 is the BHW assistant's scope and uuc-phc-2025 the UUC one (lib/ai/dataset-scope.ts);
--    the UUC dictionary is the one that spoke of StepZero. Side effect, accepted: "Last updated" on
--    those two datasets reads this migration's date.
update dim_dataset
set last_updated_at = now()
where slug in ('bhw-2025', 'uuc-phc-2025');
